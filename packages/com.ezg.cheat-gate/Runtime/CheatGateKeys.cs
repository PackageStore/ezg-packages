        /// <summary>One RSA public key. A key whose base64 does not decode is kept but never verifies anything.</summary>
        public sealed class Key
        {
            public readonly string Id;
            public readonly byte[] Modulus;
            public readonly byte[] Exponent;

            public Key(string id, string modulusBase64, string exponentBase64)
            {
                Id = id ?? string.Empty;
                Modulus = Decode(modulusBase64);
                Exponent = Decode(exponentBase64);
            }

            public bool IsUsable => Modulus != null && Modulus.Length >= 256 && Exponent != null && Exponent.Length > 0;

            private static byte[] Decode(string base64)
            {
                if (string.IsNullOrEmpty(base64)) return null;
                try
                {
                    return Convert.FromBase64String(base64);
                }
                catch (FormatException)
                {
                    return null;
                }
            }
        }
    }
