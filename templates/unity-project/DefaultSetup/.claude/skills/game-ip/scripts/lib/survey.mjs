function loadJson(file, def) {
  try {
    return JSON.parse(readText(file));
  } catch {
    return def;
  }
}

function norm(s) {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "");
}

/** Nhà cung cấp quen của package không ghi license: một đoạn tên package trùng tên nhà cung cấp (com.cysharp.unitask → unitask). */
function knownVendorOfPackage(name, vendors) {
  const segs = name.toLowerCase().split(/[.\-_]+/);
  const v = vendors.find((x) => x.match.some((m) => segs.includes(norm(m))));
  return v ? { title: v.title, kind: v.kind, author: v.author, license: v.license, notes: v.notes || null } : null;
}

/** Tách tên thành từ: camelCase, số, gạch, khoảng trắng. */
function words(s) {
  return s
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
}

/** Tên game `name` có trong đoạn đường dẫn `seg` không: chuỗi từ liên tiếp, hoặc một từ bằng (hay bắt đầu bằng, khi tên ≥ 8 ký tự) tên viết liền. */
function segmentHasName(segWords, nameWords, joined) {
  for (let i = 0; i + nameWords.length <= segWords.length; i++) {
    let ok = true;
    for (let k = 0; k < nameWords.length; k++) if (segWords[i + k] !== nameWords[k]) ok = false;
    if (ok) return true;
  }
  return segWords.some((w) => w === joined || (joined.length >= 8 && w.startsWith(joined)));
}

export async function survey({ root, settingsDir = null, assetStoreCaches = null, useDefaultCache = true, log = () => {} }) {
  const settings = settingsDir || path.join(root, "ProjectSettings");
  const t0 = Date.now();
  const projectFile = loadJson(path.join(settings, "GameIPProject.json"), null);
  const info = projectInfo(root);
  const ownNames = (projectFile && projectFile.ownNames && projectFile.ownNames.length ? projectFile.ownNames : [info.companyName, info.productName])
    .filter((n) => n && n !== "DefaultCompany" && n.length >= 3)
    .map(norm);
  const isOwn = (s) => !!s && ownNames.some((n) => norm(s).includes(n));

  log("Chỉ mục file…");
  const index = indexProject(root);
  log(`  ${index.files.length} file. Tính asset vào build…`);
  const inBuild = buildScope(index);
  const reasonCount = {};
  for (const why of inBuild.values()) {
    const k = why.startsWith("ref:") ? "ref" : why;
    reasonCount[k] = (reasonCount[k] || 0) + 1;
  }
  const assetFiles = index.files.filter((f) => f.path.startsWith("Assets/"));
  const packages = readPackages(index);
  for (const p of packages) {
    p.license = detectLicense(p.licenseFile ? readText(p.licenseFile) : "") || detectLicense(p.licenseField || "") || (p.name.startsWith("com.unity.") ? "unity-companion" : null);
    p.inBuildFiles = [...inBuild.keys()].filter((k) => k.startsWith(`Packages/${p.name}/`)).length;
    p.licenseFile = p.licenseFile ? rel(root, p.licenseFile).replace(/^Library\/PackageCache\/[^/]+/, `Packages/${p.name}`) : null;
    delete p.dir;
  }
  // Gói của công ty: tác giả là tên công ty, hoặc cùng một tác giả có ≥ 3 gói không license lấy từ registry mang tên công ty
  // (registry riêng hay mirror cả gói ngoài, nên không coi mọi gói của registry là của mình).
  const ownRegistry = (r) => !!r && norm(r).length >= 4 && ownNames.some((n) => n.includes(norm(r)) || norm(r).includes(n));
  const regAuthors = {};
  for (const p of packages) if (ownRegistry(p.registry) && !p.license && p.author) regAuthors[p.author] = (regAuthors[p.author] || 0) + 1;
  for (const p of packages) {
    if (p.name.startsWith("com.unity.")) p.own = null;
    else if (isOwn(p.author)) p.own = `tác giả ${p.author} là tên công ty`;
    else if (!p.license && p.author && ownRegistry(p.registry) && regAuthors[p.author] >= 3) p.own = `registry ${p.registry}, ${regAuthors[p.author]} gói của ${p.author} không license`;
    else p.own = null;
  }

  // ---------- Nguồn theo GUID: cache Asset Store ----------
  log("Đối chiếu GUID với cache Asset Store…");
  const caches = [...(assetStoreCaches || []), ...(useDefaultCache ? defaultAssetStoreCaches() : [])];
  const assetStore = [];
  for (const cache of caches) {
    for (const pkg of listCachedPackages(cache)) {
      let guids;
      try {
        guids = await readUnityPackageGuids(pkg.file);
      } catch (e) {
        assetStore.push({ ...pkg, error: String(e.message || e) });
        continue;
      }
      const matched = [];
      let moved = 0;
      for (const [g, orig] of guids) {
        const f = index.byGuid.get(g);
        if (!f || f.folder || !f.path.startsWith("Assets/")) continue;
        matched.push(f.path);
        if (f.path !== orig) moved++;
      }
      if (matched.length) assetStore.push({ publisher: pkg.publisher, category: pkg.category, name: pkg.name, file: pkg.file, packageEntries: guids.size, matched: matched.length, moved, inBuild: matched.filter((p) => inBuild.has(p)).length, paths: matched });
    }
  }

  // ---------- Folder bên thứ ba (đoán theo tên, file license, readme) ----------
  log("Tìm folder bên thứ ba…");
  const vendorData = loadJson(path.join(DATA, "vendors.json"), { thirdPartyRoots: [], vendors: [] });
  const vendors = [...vendorData.vendors, ...((projectFile && projectFile.vendors) || [])];
  const rootNames = new Set(vendorData.thirdPartyRoots.map(norm));
  const knownVendor = (name) => vendors.find((v) => v.match.some((m) => norm(m) === norm(name)));
  const dirs = new Set();
  for (const f of assetFiles) {
    const parts = f.path.split("/");
    for (let i = 2; i < parts.length; i++) dirs.add(parts.slice(0, i).join("/"));
  }
  const filesUnder = new Map();
  for (const f of assetFiles) {
    const parts = f.path.split("/");
    for (let i = 2; i < parts.length; i++) {
      const d = parts.slice(0, i).join("/");
      if (!filesUnder.has(d)) filesUnder.set(d, []);
      filesUnder.get(d).push(f);
    }
  }
  const candidates = new Map();
  const consider = (d, why) => {
    if (!candidates.has(d)) candidates.set(d, new Set());
    candidates.get(d).add(why);
  };
  // Folder gốc: tên kiểu "3rdParty", hoặc folder nền tảng nằm trong folder gốc (Plugins/iOS).
  const isRoot = (d) => {
    const parts = d.split("/");
    const name = norm(parts[parts.length - 1]);
    if (rootNames.has(name)) return true;
    return parts.length >= 3 && PLATFORM_DIRS.has(name) && isRoot(parts.slice(0, -1).join("/"));
  };
  const generic = new Set();
  for (const d of dirs) {
    const parts = d.split("/");
    const name = parts[parts.length - 1];
    const parent = parts[parts.length - 2];
    if (knownVendor(name)) consider(d, "tên nhà cung cấp quen");
    if (parent && parts.length >= 3 && isRoot(parts.slice(0, -1).join("/")) && !isRoot(d)) {
      consider(d, `nằm trong folder ${parent}`);
      if (GENERIC_DIRS.has(norm(name)) && !knownVendor(name)) generic.add(d);
    }
  }
  // Pack hay nằm thẳng dưới Assets (Assets/Jurassic Pack, Assets/Azure[Sky] Lite); mẫu của package nằm ở Assets/Samples/<package>.
  // Folder gốc của team (bắt đầu bằng "_", vd _Project), folder đặc biệt của Unity, folder mang tên công ty thì bỏ.
  const topOwn = (name) => name.startsWith("_") || UNITY_SPECIAL.has(norm(name)) || isOwn(name);
  for (const d of dirs) {
    const parts = d.split("/");
    if (parts.length === 3 && parts[0] === "Assets" && parts[1] === "Samples") consider(d, "mẫu import từ package (Assets/Samples)");
    if (parts.length === 2 && !topOwn(parts[1]) && PACK_NAME.test(parts[1])) consider(d, "tên kiểu pack (Pack, Lite, Free…)");
    if (parts.length === 3 && !topOwn(parts[1]) && DEMO_DIR.test(parts[2])) consider(parts.slice(0, 2).join("/"), `có folder ${parts[2]} kiểu pack`);
  }
  for (const p of packages) if (!p.license && !p.own) p.known = knownVendorOfPackage(p.name, vendors);
  for (const d of dirs) {
    if (d.split("/").length > 6) continue;
    const list = filesUnder.get(d) || [];
    const near = list.filter((f) => f.path.split("/").length - d.split("/").length <= 2);
    if (near.some((f) => /^(licen[cs]e|copying|eula|ofl)([-_. ]|$)/i.test(path.basename(f.path)))) consider(d, "có file license");
    // Readme nằm ngay trong folder, có link Asset Store hoặc câu kiểu "available on the Asset Store"; tài liệu của team chỉ nhắc
    // chữ "Asset Store" (vd "đắp asset từ Unity Asset Store") thì không tính.
    // Folder ngay dưới Assets có tài liệu kiểu pack: PDF / RTF / HTML, hoặc readme chữ có lời cảm ơn mua, email hỗ trợ, dòng bản quyền.
    // Readme của team (giải thích code) thì không tính.
    if (d.split("/").length === 2 && !topOwn(d.split("/")[1])) {
      const docs = list.filter((f) => f.path.split("/").length === 3 && /^(read ?me|documentation|manual|user ?guide)[^/]*\.(pdf|txt|md|html?|rtf)$/i.test(path.basename(f.path)));
      const packDoc = docs.some((f) => /\.(pdf|rtf|html?)$/i.test(f.path) || /thanks? (you )?for (buying|purchasing|downloading|choosing)|support@|copyright|©|\(c\) \d{4}/i.test((readText(f.abs) || "").slice(0, 20000)));
      if (packDoc) consider(d, "có tài liệu kiểu pack đi kèm");
    }
    const readmes = list.filter((f) => f.path.split("/").length - d.split("/").length === 1 && /\.(txt|md|html?|url)$/i.test(f.path) && /readme|documentation|docs?|manual|guide|getting ?started/i.test(path.basename(f.path)));
    if (readmes.length) {
      const txt = readmes.map((f) => (readText(f.abs) || "").slice(0, 20000)).join("\n");
      if (/assetstore\.unity\.com\/packages|u3d\.as\/|(available|purchased?|bought|review|rate)\b[^.\n]{0,40}\bAsset Store/i.test(txt)) consider(d, "readme nhắc Asset Store");
    }
  }
  // Chỉ giữ folder ngoài cùng; folder gốc kiểu "3rdParty" thì không tự là nhà cung cấp.
  const vendorDirs = [...candidates.keys()]
    .filter((d) => !isRoot(d) || knownVendor(d.split("/").pop()))
    .filter((d, _, all) => !all.some((o) => o !== d && d.startsWith(`${o}/`)))
    .sort();
  const vendorFolders = vendorDirs.map((d) => {
    const list = filesUnder.get(d) || [];
    const lic = list.filter((f) => LICENSE_FILE.test(path.basename(f.path)) && f.path.split("/").length - d.split("/").length <= 3);
    const licIds = lic.map((f) => ({ file: f.path, license: detectLicense(readText(f.abs)) })).slice(0, 10);
    const docs = list.filter((f) => /\.(txt|md|html?|url)$/i.test(f.path) && f.path.split("/").length - d.split("/").length <= 3).slice(0, 20);
    let storeUrl = null;
    for (const f of docs) {
      const m = (readText(f.abs) || "").match(/https?:\/\/(assetstore\.unity\.com\/packages\/[^\s"'<>)\]]+|u3d\.as\/[A-Za-z0-9]+)/);
      if (m) {
        storeUrl = m[0];
        break;
      }
    }
    const kv = knownVendor(d.split("/").pop());
    const sm = d.match(/^Assets\/Samples\/([^/]+)$/);
    const sp = sm && packages.find((p) => p.displayName === sm[1] || p.name === sm[1]);
    return {
      path: d,
      generic: generic.has(d),
      sampleOf: sp ? { name: sp.name, title: sp.displayName || sp.name, author: sp.author, license: sp.license || (sp.known && sp.known.license) || null } : null,
      evidence: [...candidates.get(d), ...(generic.has(d) ? ["tên folder chung, chưa rõ pack nào"] : [])],
      known: kv ? { title: kv.title, kind: kv.kind, author: kv.author, license: kv.license, limits: kv.limits || null, notes: kv.notes || null } : null,
      licenseFiles: licIds,
      storeUrl,
      files: list.length,
      inBuild: list.filter((f) => inBuild.has(f.path)).length,
    };
  });

  // ---------- Font ----------
  log("Đọc font…");
  const fonts = [];
  for (const f of index.files) {
    if (!FONT_EXT.test(f.path)) continue;
    const fi = readFontInfo(f.abs) || {};
    const text = [fi.license, fi.licenseUrl, fi.copyright].filter(Boolean).join(" \n ");
    const dir = f.path.slice(0, f.path.lastIndexOf("/"));
    const beside = index.files.filter((g) => g.path.startsWith(`${dir}/`) && g.path.lastIndexOf("/") === dir.length && LICENSE_FILE.test(path.basename(g.path)));
    let license = detectLicense(text);
    if (!license) for (const b of beside) license = license || (detectLicense(readText(b.abs)) === "OFL-1.1" ? "OFL-1.1" : null);
    fonts.push({
      path: f.path,
      inBuild: inBuild.has(f.path),
      family: fi.family || null,
      copyright: fi.copyright || null,
      vendor: fi.vendor || null,
      trademark: fi.trademark || null,
      licenseText: fi.license || null,
      licenseUrl: fi.licenseUrl || null,
      license,
      fsType: fi.fsType ?? null,
      embedding: embeddingOf(fi.fsType),
      licenseFilesBeside: beside.map((b) => b.path),
      reservedName: /reserved font name/i.test(fi.copyright || "") || /reserved font name/i.test(fi.license || ""),
    });
  }

  // ---------- Âm thanh ----------
  log("Đọc tag âm thanh…");
  const audio = { total: 0, inBuild: 0, tagged: [] };
  for (const f of assetFiles) {
    if (!AUDIO_EXT.test(f.path)) continue;
    audio.total++;
    if (inBuild.has(f.path)) audio.inBuild++;
    const r = readAudioTags(f.abs);
    if (!r || !Object.keys(r.tags).length) continue;
    const t = r.tags;
    const sourceLike = !!(t.copyright || t.publisher || t.url || t.copyrightUrl || t.sourceUrl || t.publisherUrl || t.artistUrl || AUDIO_SOURCE_HINT.test(Object.values(t).join(" ")));
    audio.tagged.push({ path: f.path, inBuild: inBuild.has(f.path), tags: t, sourceLike, own: isOwn(Object.values(t).join(" ")) });
  }

  // ---------- Ảnh ----------
  log("Đọc metadata ảnh…");
  const images = { total: 0, inBuild: 0, foreign: [], ai: [] };
  for (const f of assetFiles) {
    if (!IMAGE_EXT.test(f.path)) continue;
    images.total++;
    if (inBuild.has(f.path)) images.inBuild++;
    const m = readImageMeta(f.abs);
    if (!m || !Object.keys(m).length) continue;
    const creator = m.creator && !SOFTWARE_CREATOR.test(m.creator.trim()) ? m.creator : null;
    const rights = [creator, m.rights, m.credit, m.source, m.webStatement].filter(Boolean);
    if (rights.length && !rights.some(isOwn)) images.foreign.push({ path: f.path, inBuild: inBuild.has(f.path), creator, rights: m.rights || null, credit: m.credit || null, source: m.source || null, webStatement: m.webStatement || null });
    const ai = aiSignal(m);
    if (ai) images.ai.push({ path: f.path, inBuild: inBuild.has(f.path), signal: ai, software: m.software || null });
  }

  // ---------- Tên đáng ngờ, code dịch ngược, file cài đặt ----------
  log("Tìm tên đáng ngờ, code dịch ngược…");
  const vendorOf = (p) => vendorDirs.find((d) => p.startsWith(`${d}/`)) || null;
  const suspicious = [];
  for (const f of assetFiles) {
    if (!MEDIA_EXT.test(f.path)) continue;
    const base = path.basename(f.path);
    const hit = SUSPICIOUS_NAME.find(([re]) => re.test(base));
    const dirHit = SUSPICIOUS_DIR.test(f.path.slice(0, f.path.lastIndexOf("/")));
    if (hit || dirHit) suspicious.push({ path: f.path, inBuild: inBuild.has(f.path), why: hit ? hit[1] : "nằm trong folder tham khảo / tách asset", vendor: vendorOf(f.path) });
  }
  const decompiled = [];
  for (const f of index.files) {
    if (!f.path.endsWith(".cs") || f.path.startsWith("Packages/com.unity.")) continue;
    let head = "";
    try {
      const fd = fs.openSync(f.abs, "r");
      const buf = Buffer.alloc(32768);
      const n = fs.readSync(fd, buf, 0, buf.length, 0);
      fs.closeSync(fd);
      head = buf.toString("utf8", 0, n);
    } catch {
      continue;
    }
    const m = head.match(DECOMPILED);
    if (m) decompiled.push({ path: f.path, inBuild: inBuild.has(f.path), marker: m[0], vendor: vendorOf(f.path) });
  }
  const installers = [];
  const SKIP_ROOT = new Set(["library", "temp", "logs", "obj", ".git", ".vs", ".idea", "usersettings"]);
  for (const abs of walkFiles(root, { maxDepth: 6, skipDir: (n) => SKIP_ROOT.has(n.toLowerCase()) || n.startsWith(".") })) {
    if (!INSTALLER.test(abs)) continue;
    const p = rel(root, abs);
    let size = 0;
    try {
      size = fs.statSync(abs).size;
    } catch {
      /* bỏ qua */
    }
    installers.push({ path: p, size, mayBeOwnBuild: isOwn(path.basename(p)) });
  }

  // ---------- Tên game khác (IP-13) ----------
  log("Tìm tên game khác trong đường dẫn…");
  const gameNames = [
    ...(readText(path.join(DATA, "terms", "games.txt")) || "").split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("#")).map((n) => ({ name: n.trim(), from: "danh sách chung" })),
    ...((projectFile && projectFile.referenceGames) || []).map((n) => ({ name: n, from: "referenceGames" })),
    ...((projectFile && projectFile.competitors) || []).map((n) => ({ name: n, from: "competitors" })),
  ].filter((g) => !isOwn(g.name));
  const segIndex = new Map(); // đoạn → danh sách đường dẫn
  for (const f of assetFiles) {
    const parts = f.path.split("/").slice(1);
    parts[parts.length - 1] = parts[parts.length - 1].replace(/\.[^.]+$/, "");
    for (let i = 0; i < parts.length; i++) {
      const key = parts[i];
      if (!segIndex.has(key)) segIndex.set(key, { words: words(key), paths: [] });
      const e = segIndex.get(key);
      if (e.paths.length < 50) e.paths.push(f.path);
      else e.more = (e.more || 0) + 1;
    }
  }
  const gameHits = [];
  for (const g of gameNames) {
    const nw = words(g.name);
    if (!nw.length) continue;
    const joined = nw.join("");
    const segs = [];
    for (const [seg, e] of segIndex) if (segmentHasName(e.words, nw, joined)) segs.push({ segment: seg, count: e.paths.length + (e.more || 0), sample: e.paths.slice(0, 3), vendor: vendorOf(e.paths[0]) });
    if (segs.length) gameHits.push({ name: g.name, from: g.from, segments: segs.slice(0, 20) });
  }

  // ---------- File license, yêu cầu ghi công ----------
  log("Đọc file license, yêu cầu ghi công…");
  const licenseFiles = [];
  const creditDemands = [];
  for (const f of index.files) {
    if (f.pkg && !f.path.startsWith("Packages/")) continue;
    if (f.pkg && index.packages.find((p) => p.name === f.pkg && p.source === "cache")) continue;
    const base = path.basename(f.path);
    const isLic = LICENSE_FILE.test(base);
    const isDoc = /\.(txt|md)$/i.test(base) && /readme|credit|licen[cs]e|attribution|how ?to ?use|terms/i.test(base);
    if (!isLic && !isDoc) continue;
    const txt = readText(f.abs) || "";
    if (isLic) licenseFiles.push({ path: f.path, license: detectLicense(txt), vendor: vendorOf(f.path) });
    const m = txt.match(CREDIT_DEMAND);
    if (m) {
      const i = Math.max(0, m.index - 120);
      creditDemands.push({ path: f.path, snippet: txt.slice(i, m.index + 200).replace(/\s+/g, " ").trim(), vendor: vendorOf(f.path) });
    }
  }

  // ---------- Màn Credits / Licenses ----------
  log("Tìm màn Credits…");
  const credits = { texts: [], scripts: [], files: [] };
  for (const [p] of inBuild) {
    const f = index.byPath.get(p);
    if (!f) continue;
    if (/\.(prefab|unity)$/i.test(p)) {
      const txt = readText(f.abs) || "";
      for (const m of txt.matchAll(/m_[tT]ext: ['"]?([^\r\n]{0,120})/g)) if (CREDITS_TEXT.test(m[1])) credits.texts.push({ path: p, text: m[1].replace(/['"]$/, "") });
    } else if (p.endsWith(".cs") && /credit|licen[cs]e|acknowledg|thirdpartynotice|attribution/i.test(path.basename(p)) && p.startsWith("Assets/") && !vendorOf(p)) credits.scripts.push(p);
    else if (/thirdpartynotices?|credits?|licen[cs]es?|acknowledg/i.test(path.basename(p)) && /\.(txt|md|json|html?)$/i.test(p) && !vendorOf(p)) credits.files.push(p);
  }
  credits.texts = credits.texts.slice(0, 30);
  credits.found = credits.texts.length + credits.scripts.length + credits.files.length > 0;

  // ---------- Thương hiệu thật trong nội dung (IP-15) ----------
  log("Tìm thương hiệu thật trong nội dung…");
  const brands = scanBrands({ index, inBuild, vendorDirs, extra: (projectFile && projectFile.brands) || [] });

  // ---------- Sổ (nếu có) ----------
  const ledger = loadLedger(null, path.join(settings, "GameIPLedger.json"));
  const cov = ledger ? coverage(ledger, index, inBuild) : null;

  const scenes = buildScenes(root);
  const result = {
    tool: { name: "game-ip", version: VERSION },
    generatedAt: new Date().toISOString(),
    seconds: Math.round((Date.now() - t0) / 100) / 10,
    project: { root, ...info, ownNames, hasProjectFile: !!projectFile, hasLedger: !!ledger },
    counts: {
      files: index.files.length,
      assetFiles: assetFiles.length,
      inBuild: inBuild.size,
      inBuildAssets: [...inBuild.keys()].filter((k) => k.startsWith("Assets/")).length,
      byReason: reasonCount,
      scenes: scenes.length,
      scenesEnabled: scenes.filter((s) => s.enabled).length,
      buildReport: inBuild.buildReport,
    },
    assetStoreCaches: caches,
    assetStore: assetStore.map((a) => ({ ...a, paths: undefined, samplePaths: a.paths ? a.paths.slice(0, 5) : [] })),
    assetStorePaths: Object.fromEntries(assetStore.filter((a) => a.paths).map((a) => [`${a.publisher}/${a.name}`, a.paths])),
    vendorFolders,
    packages,
    fonts,
    audio,
    images,
    suspicious,
    decompiled,
    installers,
    gameNames: gameHits,
    brands,
    licenseFiles,
    creditDemands,
    credits,
    coverage: cov,
    inBuildList: [...inBuild.entries()].map(([p, why]) => ({ path: p, why })),
  };
  // Chỉ mục và tập vào build cho lệnh khác dùng lại; không ghi ra JSON.
  Object.defineProperty(result, "index", { value: index, enumerable: false });
  Object.defineProperty(result, "inBuild", { value: inBuild, enumerable: false });
  Object.defineProperty(result, "projectFile", { value: projectFile, enumerable: false });
  Object.defineProperty(result, "ledger", { value: ledger, enumerable: false });
  return result;
}
